"""Trap inventory of the TEST set (read-only; reports what the current engine emits, changes nothing).

Inputs: output.csv, scratch/run_report.json (from `python3 code/main.py`), the engine (media cache), and
sample_output.csv (only for T4, to compare compliant verifies with gold). No API calls.

    python3 code/analysis/trap_inventory.py > scratch/trap_inventory.md
"""
from __future__ import annotations

import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code"))
import main  # noqa: E402  (loads .env silently)
from agent.llm import LLM  # noqa: E402
from engine.loaders import read_csv  # noqa: E402
from engine.rules import OWNER, family  # noqa: E402

DATA = ROOT / "dataset"
SAMPLE_FAMILIES = {"account", "search", "analytics", "support", "export", "data_flow", "backup", "audit_record", "tombstone"}
RULE_FAMILY = {"CACHE_ENTRY": "cache", "EMAIL_DELIVERY_LOG": "email_delivery", "PRODUCT_TELEMETRY": "telemetry",
               "SECONDARY_IDENTIFIER": "secondary", "MARKETING_PROFILE": "marketing", "LEGAL_HOLD_RECORD": "legal_hold",
               "SUPPORT_ATTACHMENT (object storage)": "object"}
SPEC_QUOTES = [
    ("problem_statement.md", 11), ("problem_statement.md", 28), ("problem_statement.md", 29), ("problem_statement.md", 115),
    ("AGENTS.md", 199), ("AGENTS.md", 286), ("AGENTS.md", 299), ("AGENTS.md", 301),
    ("dataset/deletion_rules.csv", 13), ("dataset/deletion_rules.csv", 14), ("dataset/deletion_rules.csv", 15),
]


def line(path, n):
    return (ROOT / path).read_text(encoding="utf-8").splitlines()[n - 1].strip()


def fmt_steps(steps):
    return "\n".join(f"      {s['step_no']:2d} {s['phase']:12s} {s['system_id']:20s} {s['resource_id']:18s} "
                     f"{s['operation']:26s} {s['state']:10s} ev={s['evidence_id']!r}" for s in steps) or "      (no steps)"


def main_():
    P = print
    out = {r["case_id"]: (r["deletion_status"], json.loads(r["steps_json"])) for r in csv.DictReader(open(ROOT / "output.csv", encoding="utf-8"))}
    rep = json.load(open(ROOT / "scratch" / "run_report.json", encoding="utf-8"))
    cases = rep["cases"]
    eng, _, _ = main.build_engine(DATA, LLM(), 4)
    tests = {r["case_id"]: r for r in read_csv(DATA / "deletion_requests.csv")}
    samples = {r["case_id"]: r for r in read_csv(DATA / "sample_deletion_requests.csv")}
    allreq = {**samples, **tests}
    uid = {c: (eng.identity.resolve(r["email"]) or [None])[0] for c, r in allreq.items()}
    summary = []

    P("# Trap inventory: TEST set (generated by code/analysis/trap_inventory.py)\n")
    P(f"Engine state at generation: test status {dict(Counter(v[0] for v in out.values()))}; flags {rep['flags']}.\n")

    # ------------------------------------------------------------------ T1
    P("## T1 Families with no sample coverage\n")
    fam_cases = defaultdict(lambda: defaultdict(dict))
    for c, v in cases.items():
        for rid, val in (v.get("resources") or {}).items():
            if family(rid) not in SAMPLE_FAMILIES:
                fam_cases[family(rid)][c][rid] = val
    fams = sorted(set(RULE_FAMILY.values()) | set(fam_cases))
    for fam in fams:
        cs = fam_cases.get(fam, {})
        emitted = {c: [s for s in out[c][1] if family(s["resource_id"]) == fam] for c in cs}
        n_emit = sum(1 for c in cs if emitted[c])
        P(f"### {fam}  (owning system per R12 proposal: {OWNER.get(fam, 'n/a: no resource id family in data')})")
        P(f"- linked test cases: {len(cs)}; cases with emitted steps: {n_emit}")
        for c, rids in sorted(cs.items(), key=lambda kv: int(kv[0].split('_')[1])):
            P(f"  - {c} ({out[c][0]}): " + "; ".join(f"{rid} -> {val if isinstance(val, str) else '/'.join(o.split('_')[0] for o in val)}" for rid, val in rids.items()))
        acts = [a for a in eng.activity if family(a["resource_id"]) == fam]
        if not cs:
            P(f"- no test subject is linked to any `{fam}` resource (activity rows of this family: {len(acts)}; "
              f"none carries an identifier, and no evidence file names one)")
        summary.append((f"T1 {fam}", len(cs), n_emit, "R12 proposal + R8 (no sample)", "none" if fam not in ("legal_hold",) else "spec rule_13"))
        P()
    P("### T1 dumps (up to 2 cases per family with emitted steps)\n")
    for fam in fams:
        shown = 0
        for c, rids in sorted(fam_cases.get(fam, {}).items(), key=lambda kv: int(kv[0].split('_')[1])):
            emitted = [s for s in out[c][1] if family(s["resource_id"]) == fam]
            if not emitted or shown >= 2:
                continue
            shown += 1
            P(f"#### {fam} / {c} (uid {uid[c]}, audit_at {allreq[c]['audit_at']})")
            for rid in rids:
                P("```text")
                for rc in eng.ev.records:
                    if rid in rc.rids:
                        P(f"{rc.file_id} (captured {rc.captured_at}, {rc.kind}): {rc.text[:700]}")
                for a in eng.activity:
                    if a["resource_id"] == rid or rid in a["details"]:
                        P("activity: " + ",".join(a.values()))
                P("```")
            P("emitted steps:\n```text\n" + fmt_steps(out[c][1]) + "\n```\n")

    # ------------------------------------------------------------------ T2
    P("## T2 Legal holds\n")
    P("Spec lines mentioning legal hold / retention / retain (verbatim):\n")
    for f, n in SPEC_QUOTES:
        P(f"- {f} L{n}: \"{line(f, n)}\"")
    hold_users = ["user_218", "user_259", "user_388", "user_430", "user_458", "user_471", "user_503", "user_509"]
    reg_users = ["user_08", "user_12", "user_17", "user_21", "user_24", "user_29"]
    P("\n| user | source | case | status | legal_hold resource -> engine | steps |")
    P("|---|---|---|---|---|---|")
    hold_cases = []
    for u in hold_users + reg_users:
        for c in sorted(allreq, key=lambda x: int(x.split('_')[1])):
            if uid[c] != u:
                continue
            res = cases.get(c, {}).get("resources") or {}
            lh = {k: v for k, v in res.items() if k.startswith("legal_hold_")}
            st = out[c] if c in out else ("(sample)", [])
            ops = Counter(s["operation"] for s in st[1])
            src = "legal_hold_N record" if u in hold_users else "legal register PDF (no resource id)"
            P(f"| {u} | {src} | {c} | {st[0]} | {lh or '-'} | {dict(ops) or '-'} |")
            if u in hold_users:
                hold_cases.append(c)
    P("\nEffect: a legal hold is emitted only as VERIFY_RECORD_PRESENT (R6/A16 proposal, rule_13 RETAIN); it never creates a "
      "finding, so it cannot change status. The register PDF lists orders, not resource ids, so it yields no step.")
    lh_emitted = [c for c in hold_cases if any(s["resource_id"].startswith("legal_hold_") for s in out[c][1])]
    summary.append(("T2 legal holds", len(hold_cases), len(lh_emitted), "R6 (A16 proposal), rule_13", "spec rule_13; no sample"))
    for c in hold_cases:
        if any(s["resource_id"].startswith("legal_hold_") for s in out[c][1]):
            rid = next(s["resource_id"] for s in out[c][1] if s["resource_id"].startswith("legal_hold_"))
            P(f"\nDump: {c} {rid}\n```text")
            for rc in eng.ev.records:
                if rid in rc.rids:
                    P(f"{rc.file_id} (captured {rc.captured_at}): {rc.text[:700]}")
            P("```\nemitted steps:\n```text\n" + fmt_steps(out[c][1]) + "\n```")
            break

    # ------------------------------------------------------------------ T3
    P("\n## T3 Uncitable verifies dropped (case_45, case_53, case_55)\n")
    t3 = []
    for c in ("case_45", "case_53", "case_55"):
        fl = [f for f in cases[c].get("flags", []) if f.startswith("uncitable")]
        t3 += fl
        P(f"- {c}: status {out[c][0]}, flags {fl or 'none'}; steps:\n```text\n{fmt_steps(out[c][1])}\n```")
    all_unc = [(c, f) for c, v in cases.items() for f in v.get("flags", []) if f.startswith("uncitable")]
    P(f"- uncitable_verify_dropped flags in the whole run: {all_unc or 'none'}")
    summary.append(("T3 dropped uncitable verifies", len(all_unc), 0, "PS L127 + H4", "spec-backed"))

    # ------------------------------------------------------------------ T4
    P("\n## T4 A13: already-compliant records in INCOMPLETE cases\n")
    gold = {r["case_id"]: (r["deletion_status"], json.loads(r["steps_json"])) for r in read_csv(DATA / "sample_output.csv")}
    pred_s = {c: eng.plan(r) for c, r in samples.items()}
    comp_pred = comp_gold = 0
    comp_fams = Counter()
    for c, (gst, gsteps) in gold.items():
        if gst != "INCOMPLETE":
            continue
        rids = defaultdict(set)
        for s in pred_s[c]["steps"]:
            rids[s["resource_id"]].add(s["phase"])
        for rid, ph in rids.items():
            if ph == {"VERIFICATION"} and family(rid) not in ("account", "audit_record"):
                comp_pred += 1
                comp_fams[family(rid)] += 1
        grids = defaultdict(set)
        for s in gsteps:
            grids[s["resource_id"]].add(s["phase"])
        comp_gold += sum(1 for rid, ph in grids.items() if ph == {"VERIFICATION"} and family(rid) not in ("account", "audit_record"))
    t_comp = sum(1 for c, (st, steps) in out.items() if st == "INCOMPLETE"
                 for rid in {s["resource_id"] for s in steps}
                 if family(rid) not in ("account", "audit_record")
                 and {s["phase"] for s in steps if s["resource_id"] == rid} == {"VERIFICATION"})
    P(f"- 22 INCOMPLETE samples: compliant non-account/non-audit records with a verify-only step: predicted {comp_pred}, gold {comp_gold}")
    P(f"- predicted compliant verify-only by family: {dict(comp_fams) or '-'}")
    P(f"- test INCOMPLETE cases: compliant non-account/non-audit verify-only records emitted: {t_comp}")
    P("- Rule as implemented: `ops_for` emits the verify-only step for every linked compliant record regardless of case status "
      "(SPEC_CARD A13 interpretation: include their VERIFY step); accounts (R5/I10) and retained audit records (R6) always get theirs.")
    summary.append(("T4 A13 compliant verifies in INCOMPLETE", t_comp, t_comp, "A13 (include)", "none (0 sample examples)"))

    # ------------------------------------------------------------------ T5
    P("\n## T5 Identity traps\n")
    decoy_cases = ["case_183", "case_221"]
    upper = [c for c, r in tests.items() if r["email"] != r["email"].lower()]
    P("| case | email | resolved | how | emitted resources attributed to another user |")
    P("|---|---|---|---|---|")
    bad = 0
    for c in decoy_cases + upper:
        r = tests[c]
        how = "current" if any(u["email"].lower() == r["email"].lower() for u in eng.identity.users.values()) else "historical"
        others = []
        for rid in {s["resource_id"] for s in out[c][1]}:
            o = eng.attributed.get(rid, set()) - {uid[c]}
            if o:
                others.append(f"{rid}->{sorted(o)}")
        bad += bool(others)
        tag = "decoy-candidate" if c in decoy_cases else f"uppercase/{how}"
        P(f"| {c} | {r['email']} | {uid[c]} | {tag} | {others or 'none'} |")
    P(f"\nCases with any emitted resource that evidence also attributes to another user: {bad}")
    summary.append(("T5 identity traps", len(decoy_cases) + len(upper), bad, "R2 exact case-insensitive", "sample-backed (S case_03/28, A11)"))

    # ------------------------------------------------------------------ T6
    P("\n## T6 Multi-request users (R15)\n")
    multi = {u: rs for u, rs in eng.requests_by_user.items() if len(rs) > 1 and any(r["case_id"] in tests for r in rs)}
    for u, rs in sorted(multi.items()):
        P(f"- {u}:")
        for r in sorted(rs, key=lambda r: r["requested_at"]):
            c = r["case_id"]
            res = (cases.get(c) or {}).get("resources") or {}
            st = out[c][0] if c in out else "(sample)"
            P(f"  - {c} [{r['requested_at']} .. {r['audit_at']}] {st}: " +
              ("; ".join(f"{k}: {v if isinstance(v, str) else 'emitted'}" for k, v in sorted(res.items())) or "-"))
    summary.append(("T6 multi-request users", len(multi), len(multi), "R15", "sample-backed (S case_07/17)"))

    # ------------------------------------------------------------------ T7
    P("\n## T7 Post-audit stress files evidence_21, evidence_40\n")
    t7 = []
    for fid in ("evidence_21", "evidence_40"):
        cap = eng.ev.meta[fid]["captured_at"]
        for rc in eng.ev.records:
            if rc.file_id != fid:
                continue
            for u in eng.identity.users_in(rc.text):
                for r in eng.requests_by_user.get(u, []):
                    c = r["case_id"]
                    if c in tests and r["audit_at"] < cap and r["requested_at"] <= cap:
                        pass
                    if c in tests and r["audit_at"] < cap and any(x.startswith("legal_hold") for x in rc.rids):
                        cites = [s for s in out[c][1] if s["evidence_id"] == fid]
                        res = {k: v for k, v in ((cases.get(c) or {}).get("resources") or {}).items() if k in rc.rids}
                        t7.append(c)
                        P(f"- {fid} (captured {cap}) vs {c} (audit_at {r['audit_at']}): resources {res}; steps citing {fid}: {len(cites)}")
    P("- Both files are captured after those cases' audit_at, so R3 excludes them: the legal holds are not emitted, and no step cites them.")
    summary.append(("T7 post-audit stress files", len(set(t7)), 0, "R3", "spec-backed (AG 6.2/6.6) + S case_26/27"))

    # ------------------------------------------------------------------ T8
    P("\n## T8 COMPLETE cases with 0 steps or only one step type\n")
    zero = [c for c, (st, s) in out.items() if st == "COMPLETE" and not s]
    one = [c for c, (st, s) in out.items() if st == "COMPLETE" and s and len({x["operation"] for x in s}) == 1]
    one_types = Counter(next(iter({x["operation"] for x in out[c][1]})) for c in one)
    P(f"- COMPLETE with 0 steps: {len(zero)} {zero}")
    P(f"- COMPLETE with one step type: {len(one)}; by operation {dict(one_types)}")
    P(f"  - cases: {one}")
    summary.append(("T8 thin COMPLETE cases", len(zero) + len(one), 0, "R17 / evidence limits", "none"))

    # ------------------------------------------------------------------ T9
    P("\n## T9 Status decided by a single resource\n")
    single = []
    fam_hist = Counter()
    for c, (st, steps) in out.items():
        if st == "INCOMPLETE":
            frs = {s["resource_id"] for s in steps if s["phase"] == "FINDING"}
            if len(frs) == 1:
                single.append(c)
                fam_hist[family(next(iter(frs)))] += 1
    comp_hist = Counter(family(s["resource_id"]) for c, (st, steps) in out.items() if st == "COMPLETE" for s in steps)
    P(f"- INCOMPLETE cases whose status rests on exactly one finding resource: {len(single)} of "
      f"{sum(1 for v in out.values() if v[0] == 'INCOMPLETE')}; family histogram {dict(fam_hist)}")
    P(f"- COMPLETE cases (any one resource flipping to violating would flip them): "
      f"{sum(1 for v in out.values() if v[0] == 'COMPLETE')}; verified-resource family histogram {dict(comp_hist)}")
    summary.append(("T9 single-resource INCOMPLETE", len(single), len(single), "R4 latest admissible observation", "sample-backed"))

    # ------------------------------------------------------------------ observations (no rule changed)
    P("\n## Observations for review (no engine rule changed in this pass)\n")
    P("- **T3 resolved by media:** no verify is dropped any more. case_45 cites evidence_37 (security screenshot) for its "
      "audit records; case_53/55 became INCOMPLETE through media findings.")
    P("- **case_45 emits 6 audit records** (audit_record_001..006, all from the evidence_37 screenshot of user_03). Every "
      "sample subject has at most one audit record in gold, so this may over-report. R6 has no per-subject cap.")
    P("- **case_33 (user_18)** gets account_2373 / audit_record_8486, linked only by 2026-09-15 evidence: R15 assigns them to "
      "the latest request before that time, and R3c/H4 allow post-audit ownership. A third, unseen request of user_18 is "
      "equally plausible.")
    P("- **T4:** 28 compliant non-account records get a verify-only step inside INCOMPLETE test cases (A13 \"include\"), "
      "with zero sample examples either way.")
    P("- **T8:** 60 COMPLETE test cases consist only of VERIFY_RECORD_PRESENT (audit records). These are R17 cases where the "
      "subject's account has no evidence path.")

    # ------------------------------------------------------------------ summary
    P("\n## Summary\n")
    P("| trap | count | cases with emitted/affected steps | rule relied on | confidence |")
    P("|---|---|---|---|---|")
    for t, n, e, rule, conf in summary:
        P(f"| {t} | {n} | {e} | {rule} | {conf} |")


if __name__ == "__main__":
    main_()
