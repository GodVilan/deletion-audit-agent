"""Sample scorer. The ONLY module allowed to read dataset/sample_output.csv.

Runs the engine on the 32 sample requests and compares to the public gold:
headline = deletion_status accuracy (gate 32/32, SPEC_CARD §12); secondary = exact steps_json,
step-level P/R/F1 on 7-field tuples, evidence_id accuracy on matched steps, misses per case with the
owning rule, and flips against scratch/last_score.json. Appends a dated section to evaluation_report.md.

    python3 code/evaluation/score_sample.py [--no-report]     (module; the entry point is code/evaluation/main.py)
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code"))
from main import run  # noqa: E402

DATA = ROOT / "dataset"
LAST = ROOT / "scratch" / "last_score.json"
REPORT = ROOT / "code" / "evaluation" / "run_history.md"   # raw sections; the summary report is regenerated by main.py
FAMILY_RULE = {"account": "R5/R17", "audit_record": "R6/H4", "support": "R7/R8", "analytics": "R7/R8",
               "search": "R8", "export": "R8", "backup": "R9", "data_flow": "R10", "tombstone": "R11",
               "object": "R16", "marketing": "R16", "legal_hold": "R6"}


def tup(s):
    return (s["step_no"], s["phase"], s["system_id"], s["resource_id"], s["operation"], s["state"], s["evidence_id"])


def six(s):
    return (s["phase"], s["system_id"], s["resource_id"], s["operation"], s["state"], s["evidence_id"])


def core(s):
    return (s["phase"], s["system_id"], s["resource_id"], s["operation"], s["state"])


def owner_rule(rid):
    return FAMILY_RULE.get(rid.rsplit("_", 1)[0], "?")


def load(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return {r["case_id"]: (r["deletion_status"], json.loads(r["steps_json"])) for r in csv.DictReader(fh)}


def gold_case(case_id: str):
    """(status, steps) of one public sample case, for the golden trace diff; None for test cases."""
    return load(DATA / "sample_output.csv").get(case_id)


def gold_distribution() -> dict:
    """Aggregate shape of the public sample gold (status counts, steps per case, operation mix), so other
    modules can compare distributions without reading sample_output.csv themselves."""
    gold = load(DATA / "sample_output.csv")
    ops = Counter(s["operation"] for _, st in gold.values() for s in st)
    return {"n": len(gold), "status": dict(Counter(v[0] for v in gold.values())),
            "steps_per_case": sum(len(st) for _, st in gold.values()) / len(gold), "ops": dict(ops)}


def score(write_report: bool = True, quiet: bool = False) -> tuple[str, dict]:
    """Run the engine on the samples and score it. Returns (text, summary); optionally appends to the report."""
    pred_path = ROOT / "scratch" / "sample_pred.csv"
    rep = run(DATA / "sample_deletion_requests.csv", pred_path, DATA, quiet=True)
    gold, pred = load(DATA / "sample_output.csv"), load(pred_path)

    conf = Counter((gold[c][0], pred[c][0]) for c in gold)
    status_ok = sum(gold[c][0] == pred[c][0] for c in gold)
    exact = sum(gold[c] == pred[c] for c in gold)
    tp = fp = fn = 0
    tp6 = fp6 = fn6 = 0
    core_tp = ev_ok = 0
    seq_ok = 0
    misses = {}
    for c in sorted(gold):
        gs, ps = gold[c][1], pred[c][1]
        g7, p7 = Counter(map(tup, gs)), Counter(map(tup, ps))
        inter = sum((g7 & p7).values())
        tp += inter
        fp += sum(p7.values()) - inter
        fn += sum(g7.values()) - inter
        g6, p6 = Counter(map(six, gs)), Counter(map(six, ps))
        i6 = sum((g6 & p6).values())
        tp6 += i6
        fp6 += sum(p6.values()) - i6
        fn6 += sum(g6.values()) - i6
        seq_ok += [core(s) for s in gs] == [core(s) for s in ps]
        gcore = {core(s): s for s in gs}
        pcore = {core(s): s for s in ps}
        m = []
        for k, s in gcore.items():
            if k in pcore:
                core_tp += 1
                if pcore[k]["evidence_id"] == s["evidence_id"]:
                    ev_ok += 1
                else:
                    m.append(f"R13 evidence {s['resource_id']} {s['operation']}: gold {s['evidence_id']!r} got {pcore[k]['evidence_id']!r}")
            else:
                m.append(f"{owner_rule(s['resource_id'])} MISSING {s['phase'][:4]} {s['system_id']} {s['resource_id']} {s['operation']}")
        for k, s in pcore.items():
            if k not in gcore:
                m.append(f"{owner_rule(s['resource_id'])} EXTRA {s['phase'][:4]} {s['system_id']} {s['resource_id']} {s['operation']}")
        if gold[c][0] != pred[c][0]:
            m.insert(0, f"STATUS gold {gold[c][0]} got {pred[c][0]}")
        if m:
            misses[c] = m
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
    p6_ = tp6 / (tp6 + fp6) if tp6 + fp6 else 0.0
    r6_ = tp6 / (tp6 + fn6) if tp6 + fn6 else 0.0
    f6_ = 2 * p6_ * r6_ / (p6_ + r6_) if p6_ + r6_ else 0.0
    gold_steps = sum(len(v[1]) for v in gold.values())
    # field-level accuracy: align each gold step to the predicted step with the same (resource_id, operation);
    # per field, correct / gold steps (an unaligned gold step counts wrong for every field)
    FIELDS = ["step_no", "phase", "system_id", "resource_id", "operation", "state", "evidence_id"]
    field_ok = {f: 0 for f in FIELDS}
    for c in gold:
        pmap = {(s["resource_id"], s["operation"]): s for s in pred[c][1]}
        for g in gold[c][1]:
            p_ = pmap.get((g["resource_id"], g["operation"]))
            for f in FIELDS:
                field_ok[f] += p_ is not None and p_[f] == g[f]
    field_acc = {f: f"{field_ok[f]}/{gold_steps} ({field_ok[f] / gold_steps:.1%})" for f in FIELDS}
    summary = {
        "status_accuracy": f"{status_ok}/32", "exact_steps_json": f"{exact}/32",
        "step_P(7-field)": round(prec, 4), "step_R(7-field)": round(rec, 4), "step_F1(7-field)": round(f1, 4),
        "step_P(6-field, no step_no)": round(p6_, 4), "step_R(6-field)": round(r6_, 4), "step_F1(6-field)": round(f6_, 4),
        "core_step_recall(6-field, ignoring evidence/step_no)": f"{core_tp}/{gold_steps}",
        "evidence_id_acc_on_matched": f"{ev_ok}/{core_tp}", "sequence_exact(core order)": f"{seq_ok}/32",
        "field_accuracy (aligned by resource_id+operation; correct/gold steps)": field_acc,
        "intent_paths": dict(rep["intent_paths"]),
        "status_confusion": {f"{g}->{p}": n for (g, p), n in sorted(conf.items())},
    }
    per_case = {c: {"status": pred[c][0], "exact": gold[c] == pred[c]} for c in gold}
    flips = []
    try:
        last = json.loads(LAST.read_text(encoding="utf-8"))
        for c, v in per_case.items():
            lv = last["per_case"].get(c)
            if lv and (lv["status"] != v["status"] or lv["exact"] != v["exact"]):
                flips.append(f"{c}: gold={gold[c][0]} before={lv['status']}{'(exact)' if lv['exact'] else ''} "
                             f"after={v['status']}{'(exact)' if v['exact'] else ''}")
        headline_before = last["summary"]["status_accuracy"]
    except (OSError, ValueError, KeyError):
        headline_before = None
    LAST.parent.mkdir(exist_ok=True)
    LAST.write_text(json.dumps({"summary": summary, "per_case": per_case}, indent=1), encoding="utf-8")

    lines = ["SAMPLE SCORE"]
    lines += [f"  {k}: {v}" for k, v in summary.items()]
    lines.append("  status confusion (gold -> pred): " + ", ".join(f"{g}->{p}: {n}" for (g, p), n in sorted(conf.items())))
    lines.append(f"  headline before: {headline_before}  after: {summary['status_accuracy']}"
                 + ("" if headline_before is None else
                    ("  DROPPED" if int(summary['status_accuracy'].split('/')[0]) < int(headline_before.split('/')[0]) else "  (no drop)")))
    lines.append(f"  flipped vs last run: {flips or 'none' if headline_before else 'n/a (first run)'}")
    lines.append(f"MISSES ({len(misses)} cases)")
    for c, m in misses.items():
        lines.append(f"  {c}")
        lines += [f"     {x}" for x in m]
    text = "\n".join(lines)
    if not quiet:
        print(text)
    if write_report:
        stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%MZ")
        head = "" if REPORT.exists() and REPORT.stat().st_size else "# Run history\n"
        with open(REPORT, "a", encoding="utf-8") as fh:
            fh.write(f"{head}\n## Sample run {stamp}\n\n```text\n{text}\n```\n")
    return text, summary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-report", action="store_true")
    a = ap.parse_args()
    score(write_report=not a.no_report)


if __name__ == "__main__":
    main()
